using Lumi.AST;
using Lumi.Bytecode.Constants;
using Lumi.Bytecode.Instructions;
using Lumi.Bytecode.Locals;
using Lumi.StdLib;

namespace Lumi.Bytecode;

/// <summary>
/// Generates bytecode instructions and manages constants for a given abstract syntax tree (AST).
/// </summary>
public sealed class BytecodeGenerator
{
    private readonly List<Instruction> _instructions = new(capacity: 64);
    private readonly ConstantPool _constantPool = new();
    private readonly Dictionary<Label, List<int>> _unpatchedJumps = [];
    private readonly Dictionary<string, int> _functionAddresses = [];
    private readonly Dictionary<int, FunctionDescriptor> _functionDescriptors = [];
    private readonly Dictionary<string, int> _functionDescriptorIds = new(StringComparer.Ordinal);
    // TKey: struct name, TValue: list of field names in declaration order
    private readonly Dictionary<string, IReadOnlyList<string>> _structDefinitions = new(StringComparer.Ordinal);
    // TKey: struct name, TValue: list of field initializer expressions in declaration order (null if no initializer)
    private readonly Dictionary<string, IReadOnlyList<Node?>> _structFieldInitializers = new(StringComparer.Ordinal);
    // TKey: struct name, TValue: (TKey: method name, TValue: method entry point) pairs
    private readonly Dictionary<string, Dictionary<string, int>> _structMethodAddresses = new(StringComparer.Ordinal);
    private readonly Dictionary<string, Dictionary<string, int>> _structMethodDescriptorIds = new(StringComparer.Ordinal);
    private readonly Dictionary<int, HashSet<string>> _capturesByFunctionId = [];
    private readonly LocalManager _locals = new();
    private readonly Stack<int> _functionIdStack = [];
    private int _nextLabelId = 0;
    private int _nextFunctionId = 1;

    public IReadOnlyList<Instruction> Instructions => _instructions;
    public IReadOnlyList<Constant> Constants => _constantPool.Values;
    public IReadOnlyList<Local> Locals => _locals.AllLocals;
    public IReadOnlyDictionary<string, int> FunctionAddresses => _functionAddresses;
    public IReadOnlyDictionary<int, FunctionDescriptor> FunctionDescriptors => _functionDescriptors;
    public IReadOnlyDictionary<string, int> FunctionDescriptorIds => _functionDescriptorIds;
    public IReadOnlyDictionary<string, IReadOnlyList<string>> StructDefinitions => _structDefinitions;
    public IReadOnlyDictionary<string, IReadOnlyDictionary<string, int>> StructMethodAddresses
        => _structMethodAddresses.ToDictionary(static kvp => kvp.Key, static kvp => (IReadOnlyDictionary<string, int>)kvp.Value, StringComparer.Ordinal);
    public IReadOnlyDictionary<string, IReadOnlyDictionary<string, int>> StructMethodDescriptorIds
        => _structMethodDescriptorIds.ToDictionary(static kvp => kvp.Key, static kvp => (IReadOnlyDictionary<string, int>)kvp.Value, StringComparer.Ordinal);

    public BytecodeGenerator()
    {
        _locals.EnterScope();
    }

    /// <summary>
    /// Generates a bytecode result by traversing the specified syntax node.
    /// </summary>
    /// <param name="node">The root node of the syntax tree to generate bytecode from. Cannot be null.</param>
    /// <returns>A <see cref="BytecodeResult"/> containing the generated bytecode for the provided syntax node.</returns>
    public BytecodeResult Generate(Node node)
    {
        Visit(node);

        return BytecodeResult.FromGenerator(this);
    }

    private void Visit(Node node)
    {
        switch (node)
        {
            case Program program:
                PreRegisterStructDeclarations(program);

                for (int i = 0; i < program.Body.Count; i++)
                    Visit(program.Body[i]);
                break;

            case BlockStatement block:
                _locals.EnterScope();
                foreach (var stmt in block.Body)
                    Visit(stmt);
                _locals.ExitScope();
                break;

            case VariableDeclaration variableDeclaration:
                VisitVariableDeclaration(variableDeclaration);
                break;

            case FunctionDeclaration functionDeclaration:
                VisitFunctionDeclaration(functionDeclaration);
                break;

            case StructDeclaration structDeclaration:
                VisitStructDeclaration(structDeclaration);
                break;

            case CallExpression callExpression:
                VisitCallExpression(callExpression);
                break;

            case IdentifierNode identifier:
                if (_locals.LookupLocalWithScope(identifier.Name) is { } localResolution)
                {
                    RegisterCapture(localResolution);
                    Emit(Instruction.LoadVar(localResolution.Local.Label));
                    break;
                }

                if (StandardLibraryRegistry.TryGetPreludeGlobal(identifier.Name, out _))
                {
                    Emit(Instruction.LoadPreludeGlobal(identifier.Name));
                    break;
                }
                throw BytecodeError.UndefinedVariable(identifier.Name);

            case NewExpression newExpression:
                VisitNewExpression(newExpression);
                break;

            case MemberExpression memberExpression:
                VisitMemberExpression(memberExpression);
                break;

            case PrintStatement printStatement:
                Visit(printStatement.Argument);
                Emit(new Instruction(InstructionKind.Print));
                break;

            case IfStatement ifStatement:
                VisitIfStatement(ifStatement);
                break;

            case ForStatement forStatement:
                VisitForStatement(forStatement);
                break;

            case ReturnStatement returnStatement:
                VisitReturnStatement(returnStatement);
                break;

            case NumberNode number:
                Emit(Instruction.PushConst(AddConstant(Constant.FromNumber(number.Value))));
                break;

            case BooleanNode boolean:
                Emit(Instruction.PushConst(AddConstant(Constant.FromBoolean(boolean.Value))));
                break;

            case StringNode str:
                Emit(Instruction.PushConst(AddConstant(Constant.FromString(str.Value))));
                break;

            case ArrayLiteral arrayLiteral:
                VisitArrayLiteral(arrayLiteral);
                break;

            case IndexExpression indexExpression:
                Visit(indexExpression.Object);
                Visit(indexExpression.Index);
                Emit(Instruction.IndexArray());
                break;

            case ExpressionStatement expressionStatement:
                Visit(expressionStatement.Expression);

                if (ExpressionLeavesValue(expressionStatement.Expression))
                {
                    Emit(Instruction.Pop());
                }

                break;

            case UnaryExpression unaryExpression:
                VisitUnaryExpression(unaryExpression);
                break;

            case BinaryExpression binaryExpression:
                VisitBinaryExpression(binaryExpression);
                break;
            case AssignmentExpression assignmentExpression:
                // Target is a variable (e.g. x = value)
                if (assignmentExpression.Left is IdentifierNode targetIdentifier)
                {
                    Visit(assignmentExpression.Right);
                    var targetResolution = _locals.LookupLocalWithScope(targetIdentifier.Name) ?? throw BytecodeError.UndefinedVariable(targetIdentifier.Name);
                    RegisterCapture(targetResolution);
                    Emit(Instruction.StoreVar(targetResolution.Local.Label));
                    break;
                }

                // Target is a struct field (e.g. myStruct.field = value)
                if (assignmentExpression.Left is MemberExpression memberAssignment)
                {
                    Visit(memberAssignment.Object);
                    Visit(assignmentExpression.Right);
                    Emit(Instruction.StoreField(memberAssignment.Property.Name));
                    break;
                }

                throw BytecodeError.InvalidAssignmentTarget();

            default:
                break;
        }
    }

    private void PreRegisterStructDeclarations(Program program)
    {
        foreach (var statement in program.Body)
        {
            if (statement is not StructDeclaration structDeclaration)
                continue;

            var structName = structDeclaration.Identifier.Name;
            if (_structDefinitions.ContainsKey(structName))
                throw BytecodeError.StructAlreadyDefined(structName);

            var fields = structDeclaration.Fields.Select(static f => f.Identifier.Name).ToArray();
            var fieldInitializers = structDeclaration.Fields.Select(static f => f.Init).ToArray();
            _structDefinitions[structName] = fields;
            _structFieldInitializers[structName] = fieldInitializers;
            _structMethodAddresses[structName] = new Dictionary<string, int>(StringComparer.Ordinal);
            _structMethodDescriptorIds[structName] = new Dictionary<string, int>(StringComparer.Ordinal);
        }
    }

    /// <summary>Allocates a fresh jump label whose target will be resolved later via <see cref="PatchLabel"/>.</summary>
    private Label NewLabel() => new(_nextLabelId++);

    /// <summary>Emits an unconditional jump to <paramref name="target"/>, recording it for back-patching.</summary>
    private void EmitJump(Label target)
    {
        _unpatchedJumps.TryAdd(target, []);
        _unpatchedJumps[target].Add(_instructions.Count);
        Emit(Instruction.Jump(0));
    }

    /// <summary>Emits a conditional jump that jumps to <paramref name="target"/> when the top-of-stack is false.</summary>
    private void EmitJumpIfFalse(Label target)
    {
        _unpatchedJumps.TryAdd(target, []);
        _unpatchedJumps[target].Add(_instructions.Count);
        Emit(Instruction.JumpIfFalse(0));
    }

    /// <summary>
    /// Resolves all jumps that target <paramref name="label"/> to point at the current instruction position,
    /// then removes the label from the unpatched table.
    /// </summary>
    private void PatchLabel(Label label)
    {
        if (!_unpatchedJumps.TryGetValue(label, out var sites))
            return;

        var target = _instructions.Count;
        foreach (var site in sites)
        {
            var old = _instructions[site];
            _instructions[site] = new Instruction(old.Kind, intOperand: target);
        }

        _unpatchedJumps.Remove(label);
    }

    /// <summary>Emit an instruction.</summary>
    private void Emit(Instruction instruction) => _instructions.Add(instruction);

    /// <summary>Adds a new constant.</summary>
    private int AddConstant(Constant constant) => _constantPool.Add(constant);

    private void VisitForStatement(ForStatement forStatement)
    {
        _locals.EnterScope();

        if (forStatement.Iterator is null)
            throw BytecodeError.ForStatementMissingIterator();

        if (forStatement.Iterator is not IdentifierNode)
            throw BytecodeError.NoValidIteratorFound();

        var iteratorName = ((IdentifierNode)forStatement.Iterator).Name;
        var varIdx = _locals.GetOrCreateLocal(iteratorName, LocalKind.Var, VarType.Int);

        // Store the start value into the iterator variable.
        Visit(forStatement.Start);
        Emit(Instruction.StoreVar(varIdx));

        // Store the end bound in a hidden local.
        var endIdx = _locals.GetOrCreateLocal("$end", LocalKind.Let, VarType.Int);
        Visit(forStatement.End);
        Emit(Instruction.StoreVar(endIdx));

        // Store the step value in a hidden local (defaults to 1).
        var stepIdx = _locals.GetOrCreateLocal("$step", LocalKind.Let, VarType.Int);
        if (forStatement.Step is not null)
        {
            Visit(forStatement.Step);
        }
        else
        {
            Emit(Instruction.PushConst(AddConstant(Constant.FromNumber(1))));
        }
        Emit(Instruction.StoreVar(stepIdx));

        // Record the loop-header position for the backward jump.
        var loopStart = _instructions.Count;
        var endLabel = NewLabel();

        // Condition: iterator <= end
        Emit(Instruction.LoadVar(varIdx));
        Emit(Instruction.LoadVar(endIdx));
        Emit(new Instruction(InstructionKind.Leq));

        EmitJumpIfFalse(endLabel);

        // Body
        Visit(forStatement.Body);

        // Increment: iterator = iterator + step
        Emit(Instruction.LoadVar(varIdx));
        Emit(Instruction.LoadVar(stepIdx));
        Emit(Instruction.Add());
        Emit(Instruction.StoreVar(varIdx));

        // Jump back to condition check.
        Emit(Instruction.Jump(loopStart));
        PatchLabel(endLabel);

        _locals.ExitScope();
    }

    private void VisitIfStatement(IfStatement ifStatement)
    {
        _locals.EnterScope();

        // Evaluate the condition — leaves a bool on the stack.
        Visit(ifStatement.Expr);

        var elseLabel = NewLabel();
        EmitJumpIfFalse(elseLabel);   // jump past the then-branch if condition is false

        Visit(ifStatement.Stmt);      // then-branch

        if (ifStatement.ElsePart is not null)
        {
            var endLabel = NewLabel();
            EmitJump(endLabel);        // jump past else-branch after then-branch executes
            PatchLabel(elseLabel);     // else-branch starts here
            Visit(ifStatement.ElsePart);
            PatchLabel(endLabel);      // end of if/else
        }
        else
        {
            PatchLabel(elseLabel);     // no else: target lands right after then-branch
        }

        _locals.ExitScope();
    }

    private void VisitArrayLiteral(ArrayLiteral arrayLiteral)
    {
        foreach (var element in arrayLiteral.Elements)
        {
            Visit(element);
        }

        Emit(Instruction.MakeArray(arrayLiteral.Elements.Count));
    }

    private void VisitVariableDeclaration(VariableDeclaration variableDeclaration)
    {
        foreach (var declaration in variableDeclaration.Declarations)
        {
            if (declaration.VarName is not IdentifierNode varName)
                throw BytecodeError.ExpectedIdentifierInVariableDeclaration();

            var localKind = variableDeclaration.Kind switch
            {
                "var" => LocalKind.Var,
                "const" => LocalKind.Const,
                _ => LocalKind.Let,
            };

            var type = declaration.VarType is IdentifierNode varType
                ? VarTypeExtensions.Parse(varType.Name)
                : VarType.Unknown;

            if (declaration.Init is not null)
            {
                // Emit code to evaluate the initializer so the value is on the stack, then store it.
                Visit(declaration.Init);
                Emit(Instruction.StoreVar(_locals.GetOrCreateLocal(varName.Name, localKind, type)));
            }
            else
            {
                // Type-annotated declaration with no initializer: register the local but emit no instructions.
                _locals.GetOrCreateLocal(varName.Name, localKind, type);
            }
        }
    }

    private void VisitUnaryExpression(UnaryExpression unaryExpression)
    {
        Visit(unaryExpression.Argument);

        var kind = unaryExpression.Operator switch
        {
            "-" => InstructionKind.Negate,
            "!" => InstructionKind.Not,
            _ => throw BytecodeError.UnsupportedOperator(unaryExpression.Operator)
        };

        Emit(new Instruction(kind));
    }

    private void VisitBinaryExpression(BinaryExpression binaryExpression)
    {
        Visit(binaryExpression.Left);   // Evaluate left side
        Visit(binaryExpression.Right);  // Evaluate right side

        var kind = binaryExpression.Operator switch
        {
            "+" => InstructionKind.Add,
            "-" => InstructionKind.Sub,
            "*" => InstructionKind.Mul,
            "/" => InstructionKind.Div,
            "%" => InstructionKind.Mod,
            "==" => InstructionKind.Eq,
            "!=" => InstructionKind.Neq,
            "<" => InstructionKind.Lt,
            ">" => InstructionKind.Gt,
            "<=" => InstructionKind.Leq,
            ">=" => InstructionKind.Geq,
            _ => throw BytecodeError.UnsupportedOperator(binaryExpression.Operator)
        };

        Emit(new Instruction(kind));    // Emit the operator instruction, which will consume the two operands from the stack
    }

    private void VisitFunctionDeclaration(FunctionDeclaration functionDeclaration)
    {
        if (functionDeclaration.Id is not IdentifierNode functionName)
            throw BytecodeError.ExpectedIdentifierInFunctionDeclaration();

       var descriptor= VisitFunctionBody(
            functionDeclaration,
            descriptor =>
            {
                _functionAddresses[functionName.Name] = descriptor.EntryPoint;

                if (descriptor.ParentFunctionId is null && descriptor.OwningStructName is null)
                {
                    _functionDescriptorIds[functionName.Name] = descriptor.FunctionId;
                }
            },
            receiverLocalName: null,
            owningStructName: null);

        // TODO:  It does not yet switch captured identifier codegen to LoadCapture;
        // right now it still records captures while emitting the existing local access path.
        if (descriptor.ParentFunctionId is not null && descriptor.HasCaptures())
        {
            Emit(Instruction.MakeClosure(descriptor.FunctionId));
        }
    }

    private FunctionDescriptor VisitFunctionBody(
        FunctionDeclaration functionDeclaration,
        Action<FunctionDescriptor> registerDescriptor,
        string? receiverLocalName,
        string? owningStructName)
    {
        // Jump over the function body so it isn't executed during normal program flow.
        var skipLabel = NewLabel();
        EmitJump(skipLabel);

        var functionId = _nextFunctionId++;
        int? parentFunctionId = _functionIdStack.Count > 0 ? _functionIdStack.Peek() : null;
        var entryPoint = _instructions.Count;

        if (functionDeclaration.Id is not IdentifierNode functionName)
            throw BytecodeError.ExpectedIdentifierInFunctionDeclaration();

        var descriptor = new FunctionDescriptor(
            FunctionId: functionId,
            Name: functionName.Name,
            EntryPoint: entryPoint,
            ParameterCount: functionDeclaration.Params.Count,
            ParentFunctionId: parentFunctionId,
            OwningStructName: owningStructName,
            CaptureNames: []);

        _functionDescriptors[functionId] = descriptor;
        registerDescriptor(descriptor);
        _functionIdStack.Push(functionId);

        try
        {
            // Reset the slot counter so function-local variables are numbered from 0,
            // relative to the function's base pointer at runtime.
            var savedSlotCounter = _locals.SaveAndResetSlotCounter();

            try
            {
                // Create a new scope for the function body.
                _locals.EnterScope(functionId);

                // Register parameters as locals and emit StoreVar instructions
                // to pop the caller's arguments into them.
                // Arguments are pushed left-to-right, so we pop right-to-left.
                var parameterLabels = new List<Label>(functionDeclaration.Params.Count);
                if (receiverLocalName is not null)
                    parameterLabels.Add(_locals.GetOrCreateLocal(receiverLocalName, LocalKind.Let, VarType.Unknown));

                foreach (var param in functionDeclaration.Params)
                {
                    if (param is not IdentifierNode paramName)
                        throw BytecodeError.ExpectedIdentifierInFunctionParameter();

                    parameterLabels.Add(_locals.GetOrCreateLocal(paramName.Name, LocalKind.Var, VarType.Unknown));
                }

                for (int i = parameterLabels.Count - 1; i >= 0; i--)
                {
                    Emit(Instruction.StoreVar(parameterLabels[i]));
                }

                // Generate bytecode for the function body.
                Visit(functionDeclaration.Body);

                // Implicit return: push undefined and return.
                Emit(Instruction.PushConst(AddConstant(Constant.Undefined())));
                Emit(new Instruction(InstructionKind.Return));

                _locals.ExitScope();
            }
            finally
            {
                // Restore the global slot counter so outer-scope numbering resumes correctly.
                _locals.RestoreSlotCounter(savedSlotCounter);
            }

            descriptor = descriptor with
            {
                CaptureNames = GetOrderedCaptures(functionId)
            };
            _functionDescriptors[functionId] = descriptor;

            // Patch the skip-jump so normal execution resumes here.
            PatchLabel(skipLabel);
        }
        finally
        {
            _functionIdStack.Pop();
        }

        return descriptor;
    }

    private void RegisterCapture(LocalResolution resolution)
    {
        if (_functionIdStack.Count == 0)
            return;

        var currentFunctionId = _functionIdStack.Peek();
        if (resolution.OwningFunctionId is null || resolution.OwningFunctionId == currentFunctionId)
            return;

        if (!_capturesByFunctionId.TryGetValue(currentFunctionId, out var captures))
        {
            captures = new HashSet<string>(StringComparer.Ordinal);
            _capturesByFunctionId[currentFunctionId] = captures;
        }

        captures.Add(resolution.Local.Name);
    }

    private IReadOnlyList<string> GetOrderedCaptures(int functionId)
    {
        if (!_capturesByFunctionId.TryGetValue(functionId, out var captures) || captures.Count == 0)
            return [];

        return [.. captures.OrderBy(static name => name, StringComparer.Ordinal)];
    }

    private void VisitCallExpression(CallExpression callExpression)
    {
        if (callExpression.Callee is IdentifierNode functionName)
        {
            // Push arguments left-to-right.
            foreach (var arg in callExpression.Arguments)
            {
                Visit(arg);
            }

            // Emit the call.
            Emit(new Instruction(InstructionKind.CallFn, functionName.Name));
            return;
        }

        if (callExpression.Callee is not MemberExpression memberExpression)
            throw BytecodeError.ExpectedIdentifierInFunctionCall();

        if (memberExpression.Property is not IdentifierNode methodIdentifier)
            throw BytecodeError.ExpectedIdentifierInMemberAccess();

        // First push object
        // Then push any arguments left to right
        // Then push the call instruction
        Visit(memberExpression.Object);

        foreach (var arg in callExpression.Arguments)
        {
            Visit(arg);
        }

        Emit(Instruction.CallMemberMethod(methodIdentifier.Name, callExpression.Arguments.Count));
    }

    private static bool ExpressionLeavesValue(Node expression) => expression is not AssignmentExpression;

    private void VisitStructDeclaration(StructDeclaration structDeclaration)
    {
        var structName = structDeclaration.Identifier.Name;
        if (!_structDefinitions.ContainsKey(structName))
            _structDefinitions[structName] = [.. structDeclaration.Fields.Select(static f => f.Identifier.Name)];

        _structFieldInitializers.TryAdd(structName, [.. structDeclaration.Fields.Select(static f => f.Init)]);

        _structMethodAddresses.TryAdd(structName, new Dictionary<string, int>(StringComparer.Ordinal));

        foreach (var method in structDeclaration.Methods)
        {
            if (method.Id is not IdentifierNode methodName)
                throw BytecodeError.ExpectedIdentifierInFunctionDeclaration();

            // The method body will be emitted as a regular function, but we register its entry point in the _structMethodAddresses table
            // so it can be called via CallMemberMethod instructions.
            VisitFunctionBody(
                method,
                descriptor =>
                {
                    _structMethodAddresses[structName][methodName.Name] = descriptor.EntryPoint;
                    _structMethodDescriptorIds[structName][methodName.Name] = descriptor.FunctionId;
                },
                receiverLocalName: "this",
                owningStructName: structName);
        }
    }

    private void VisitNewExpression(NewExpression newExpression)
    {
        var structName = newExpression.TypeName.Name;
        if (!_structDefinitions.TryGetValue(structName, out var fields))
            throw BytecodeError.UndefinedStruct(structName);

        var hasNamedArguments = newExpression.Arguments.Any(static a => a is StructFieldInitializerArgument);
        if (hasNamedArguments)
        {
            if (newExpression.Arguments.Any(static a => a is not StructFieldInitializerArgument))
                throw BytecodeError.InvalidStructConstructorArgumentsMixing(structName);

            var namedArguments = new Dictionary<string, Node>(StringComparer.Ordinal);
            foreach (var argument in newExpression.Arguments)
            {
                var named = (StructFieldInitializerArgument)argument;
                namedArguments[named.Identifier.Name] = named.Value;
            }

            _structFieldInitializers.TryGetValue(structName, out var fieldInitializers);

            for (int i = 0; i < fields.Count; i++)
            {
                var fieldName = fields[i];
                if (namedArguments.TryGetValue(fieldName, out var providedValue))
                {
                    Visit(providedValue);
                    continue;
                }

                var initializer = fieldInitializers is not null && i < fieldInitializers.Count
                    ? fieldInitializers[i]
                    : null;

                if (initializer is null)
                {
                    Emit(Instruction.PushConst(AddConstant(Constant.Undefined())));
                }
                else
                {
                    Visit(initializer);
                }
            }

            Emit(Instruction.NewStruct(structName, fields.Count));
            return;
        }

        var argumentCount = newExpression.Arguments.Count;
        if (argumentCount > fields.Count)
            throw BytecodeError.StructConstructorArgumentCountMismatch(structName, fields.Count, argumentCount);

        foreach (var argument in newExpression.Arguments)
            Visit(argument);

        // NOTE: if there are missing arguments, we have two options:
        // 1) Materialize them as undefined values on the stack, so the constructor can access them as normal parameters.
        // 2) Leave them off the stack and have the constructor know to treat missing arguments as undefined.
        var materializeMissingArguments = false;
        if (argumentCount < fields.Count && _structFieldInitializers.TryGetValue(structName, out var fieldInitializersPositional))
        {
            for (int i = argumentCount; i < fieldInitializersPositional.Count; i++)
            {
                if (fieldInitializersPositional[i] is not null)
                {
                    materializeMissingArguments = true;
                    break;
                }
            }

            if (materializeMissingArguments)
            {
                for (int i = argumentCount; i < fieldInitializersPositional.Count; i++)
                {
                    var initializer = fieldInitializersPositional[i];
                    if (initializer is null)
                    {
                        Emit(Instruction.PushConst(AddConstant(Constant.Undefined())));
                        continue;
                    }

                    Visit(initializer);
                }
            }
        }

        Emit(Instruction.NewStruct(structName, materializeMissingArguments ? fields.Count : argumentCount));
    }

    private void VisitMemberExpression(MemberExpression memberExpression)
    {
        Visit(memberExpression.Object);
        Emit(Instruction.LoadField(memberExpression.Property.Name));
    }

    private void VisitReturnStatement(ReturnStatement returnStatement)
    {
        // If there's a return value, evaluate it and leave it on the stack.
        if (returnStatement.Argument != null)
        {
            Visit(returnStatement.Argument);
        }
        else
        {
            // No explicit return value: push undefined
            Emit(Instruction.PushConst(AddConstant(Constant.Undefined())));
        }

        // Emit the return instruction
        Emit(new Instruction(InstructionKind.Return));
    }
}
